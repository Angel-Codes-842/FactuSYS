create or replace function public.current_tenant_id()
returns bigint
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with miembro as (
    select tenant_id, rol, sucursal_id
      from public.tenant_miembros
     where user_id = auth.uid() and activo
  )
  select coalesce(
    -- El claim solo cuenta si el usuario también es miembro de ese tenant.
    (select m.tenant_id
       from miembro m
      where m.tenant_id = nullif(current_setting('request.jwt.claim.tenant_id', true), '')::bigint),
    (select p.tenant_activo_id
       from public.perfiles p
       join miembro m on m.tenant_id = p.tenant_activo_id
      where p.id = auth.uid() and p.activo),
    (select tenant_id from miembro order by tenant_id limit 1)
  );
$$;

create or replace function public.current_tenant_rol()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  -- Sin membresía en el tenant activo no hay rol: un claim JWT manipulado
  -- no puede convertir a alguien en admin del tenant ajeno.
  select coalesce(
    (select rol
       from public.tenant_miembros
      where user_id = auth.uid()
        and tenant_id = public.current_tenant_id()
        and activo
      limit 1),
    'anon'
  );
$$;

create or replace function public.current_tipo()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.current_tenant_rol();
$$;

create or replace function public.current_sucursal_id()
returns bigint
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce(
    (select sucursal_id
       from public.tenant_miembros
      where user_id = auth.uid()
        and tenant_id = public.current_tenant_id()
        and activo
      limit 1),
    (select sucursal_id from public.perfiles where id = auth.uid() and activo)
  );
$$;

create or replace function public.cambiar_tenant_activo(p_tenant_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1 from public.tenant_miembros
     where user_id = auth.uid() and tenant_id = p_tenant_id and activo
  ) then
    raise exception 'No sos miembro activo del tenant %', p_tenant_id
      using errcode = '42501';
  end if;

  update public.perfiles
     set tenant_activo_id = p_tenant_id
   where id = auth.uid();
end $$;

revoke all on function public.current_tenant_id() from public;
revoke all on function public.current_tenant_rol() from public;
revoke all on function public.current_tipo() from public;
revoke all on function public.current_sucursal_id() from public;
revoke all on function public.cambiar_tenant_activo(bigint) from public;

grant execute on function public.current_tenant_id() to authenticated, service_role;
grant execute on function public.current_tenant_rol() to authenticated, service_role;
grant execute on function public.current_tipo() to authenticated, service_role;
grant execute on function public.current_sucursal_id() to authenticated, service_role;
grant execute on function public.cambiar_tenant_activo(bigint) to authenticated, service_role;

-- Altas futuras en Auth: perfil + membresía en el tenant 1 (o el que indique
-- raw_user_meta_data->>'tenant_id').
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_tenant_id bigint := coalesce(
    nullif(new.raw_user_meta_data ->> 'tenant_id', '')::bigint,
    1
  );
begin
  insert into public.perfiles (
    id, username, email, first_name, last_name, tipo, tenant_activo_id
  )
  values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'username', ''),
      split_part(coalesce(new.email, ''), '@', 1),
      new.id::text
    ),
    new.email,
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    coalesce(new.raw_user_meta_data ->> 'tipo', 'vendedor'),
    v_tenant_id
  )
  on conflict (id) do nothing;

  if exists (select 1 from public.tenants where id = v_tenant_id) then
    insert into public.tenant_miembros (user_id, tenant_id, rol, activo)
    values (
      new.id,
      v_tenant_id,
      coalesce(new.raw_user_meta_data ->> 'tipo', 'vendedor'),
      true
    )
    on conflict (user_id, tenant_id) do nothing;
  end if;

  return new;
end $$;

