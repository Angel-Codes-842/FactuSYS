-- 0010 — Multitenant real: una empresa = un tenant.
--
-- Se ejecuta después de 0009_cheques.sql. Idempotente.
--
-- Los datos existentes pasan al tenant 1 (la empresa actual). La identidad
-- sigue en Supabase Auth; la pertenencia a empresas vive en tenant_miembros.
-- El tenant activo se resuelve, en orden: claim JWT `tenant_id`,
-- perfiles.tenant_activo_id y, como último recurso, la primera membresía.
--
-- FORCE ROW LEVEL SECURITY por sí solo NO basta: las RPCs SECURITY DEFINER
-- pertenecen a un rol con BYPASSRLS. Por eso al final se les cambia el dueño
-- a `factusys_rpc` (sin BYPASSRLS, miembro de `authenticated`), de modo que
-- sus SELECT/INSERT/UPDATE quedan sujetos a las políticas del tenant activo.
-- service_role sí puede saltarse RLS: las Edge Functions deben validar
-- memberships explícitamente.

begin;

-- ---------------------------------------------------------------------------
-- 1. Empresas y membresías.
-- ---------------------------------------------------------------------------

create table if not exists public.tenants (
  id bigint generated by default as identity primary key,
  nombre text not null,
  ruc text not null default '',
  activo boolean not null default true,
  creado timestamptz not null default now()
);

insert into public.tenants (id, nombre, ruc)
select 1,
       coalesce((select nombre from public.empresa_configuracionempresa limit 1), 'FactuSYS'),
       coalesce((select ruc from public.empresa_configuracionempresa limit 1), '')
where not exists (select 1 from public.tenants where id = 1);

select setval(
  pg_get_serial_sequence('public.tenants', 'id'),
  (select max(id) from public.tenants),
  true
);

alter table public.perfiles
  add column if not exists tenant_activo_id bigint references public.tenants (id) on delete set null;

update public.perfiles set tenant_activo_id = 1 where tenant_activo_id is null;

create table if not exists public.tenant_miembros (
  user_id uuid not null references auth.users (id) on delete cascade,
  tenant_id bigint not null references public.tenants (id) on delete cascade,
  rol text not null default 'vendedor' check (rol in ('admin', 'vendedor')),
  sucursal_id bigint references public.sucursales_sucursal (id) on delete set null,
  activo boolean not null default true,
  creado timestamptz not null default now(),
  primary key (user_id, tenant_id)
);

create index if not exists tenant_miembros_tenant_idx
  on public.tenant_miembros (tenant_id, activo);

insert into public.tenant_miembros (user_id, tenant_id, rol, sucursal_id, activo)
select p.id, 1, p.tipo, p.sucursal_id, p.activo
  from public.perfiles p
on conflict (user_id, tenant_id) do update
   set rol = excluded.rol,
       sucursal_id = excluded.sucursal_id,
       activo = excluded.activo;

