drop view if exists public.v_cajas;
create view public.v_cajas with (security_invoker = true) as
with resumen as (
  select c.id as caja_id,
         coalesce((
           select sum(f.total)
             from public.facturacion_factura f
            where not f.anulada
              and f.tenant_id = c.tenant_id
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as ventas_total,
         coalesce((
           select sum(p.monto)
             from public.facturacion_pago p
             join public.facturacion_factura f on f.id = p.factura_id
            where not f.anulada
              and f.tenant_id = c.tenant_id
              and p.metodo = 'efectivo'
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as efectivo_total,
         coalesce((
           select sum(p.monto)
             from public.facturacion_pago p
             join public.facturacion_factura f on f.id = p.factura_id
            where not f.anulada
              and f.tenant_id = c.tenant_id
              and p.metodo = 'transferencia'
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as transferencia_total,
         coalesce((
           select sum(p.monto)
             from public.facturacion_pago p
             join public.facturacion_factura f on f.id = p.factura_id
            where not f.anulada
              and f.tenant_id = c.tenant_id
              and p.metodo in ('tarjeta_pos', 'tarjeta')
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as tarjeta_total,
         coalesce((
           select sum(p.monto)
             from public.facturacion_pago p
             join public.facturacion_factura f on f.id = p.factura_id
            where not f.anulada
              and f.tenant_id = c.tenant_id
              and p.metodo = 'cheque'
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as cheque_total,
         coalesce((
           select sum(g.monto)
             from public.caja_gasto g
            where g.caja_id = c.id and g.tenant_id = c.tenant_id
         ), 0) as gastos_total
    from public.caja_caja c
)
select c.*,
       r.ventas_total,
       r.efectivo_total,
       r.transferencia_total,
       r.tarjeta_total,
       r.cheque_total,
       r.gastos_total,
       c.monto_inicial + r.efectivo_total - r.gastos_total as monto_final_esperado,
       c.monto_final_real - (c.monto_inicial + r.efectivo_total - r.gastos_total) as diferencia,
       exists (select 1 from public.caja_arqueo a where a.caja_id = c.id and a.tenant_id = c.tenant_id) as tiene_arqueo,
       coalesce(s.nombre, '') as sucursal_nombre,
       pa.username as usuario_apertura_nombre,
       pc.username as usuario_cierre_nombre
  from public.caja_caja c
  join resumen r on r.caja_id = c.id
  left join public.sucursales_sucursal s on s.id = c.sucursal_id and s.tenant_id = c.tenant_id
  left join public.perfiles pa on pa.id = c.usuario_apertura_id
  left join public.perfiles pc on pc.id = c.usuario_cierre_id;

grant select on public.v_cajas to authenticated;

-- El contrato de /auth/usuarios/me/ incorpora el tenant activo para que el SPA
-- sepa qué empresa está usando y pueda resaltarla en el selector.
create or replace view public.v_usuarios with (security_invoker = true) as
select p.id, p.username, p.email, p.first_name, p.last_name, p.tipo,
       p.telefono, p.direccion, p.sucursal_id as sucursal,
       p.activo as is_active, p.activo, '[]'::jsonb as roles,
       p.created_at as date_joined,
       p.tenant_activo_id
  from public.perfiles p;

grant select on public.v_usuarios to authenticated;

create or replace function public.caja_pendientes()
returns jsonb
language sql
stable
set search_path = public, pg_temp
as $$
  select coalesce(jsonb_agg(to_jsonb(v) order by v.fecha_apertura), '[]'::jsonb)
    from public.v_cajas v
   where v.estado = 'abierta'
     and (v.fecha_apertura at time zone 'America/Asuncion')::date
         < (now() at time zone 'America/Asuncion')::date;
$$;

revoke all on function public.caja_pendientes() from public;
grant execute on function public.caja_pendientes() to authenticated;

-- ---------------------------------------------------------------------------
-- 6. RLS por tenant.
-- ---------------------------------------------------------------------------

alter table public.tenants enable row level security;
drop policy if exists tenant_select_tenants on public.tenants;
create policy tenant_select_tenants on public.tenants
  for select to authenticated
  using (
    id = public.current_tenant_id()
    or exists (
      select 1 from public.tenant_miembros m
       where m.tenant_id = public.tenants.id
         and m.user_id = auth.uid()
         and m.activo
    )
  );
grant select on public.tenants to authenticated;

alter table public.tenant_miembros enable row level security;
drop policy if exists tenant_select_miembros on public.tenant_miembros;
create policy tenant_select_miembros on public.tenant_miembros
  for select to authenticated
  using (
    user_id = auth.uid()
    or (public.current_tenant_rol() = 'admin' and tenant_id = public.current_tenant_id())
  );
grant select on public.tenant_miembros to authenticated;

drop policy if exists perfiles_select on public.perfiles;
create policy perfiles_select on public.perfiles
  for select to authenticated
  using (
    id = auth.uid()
    or (
      public.current_tenant_rol() = 'admin'
      and exists (
        select 1 from public.tenant_miembros m
         where m.user_id = public.perfiles.id
           and m.tenant_id = public.current_tenant_id()
      )
    )
  );

create or replace function public.proteger_perfil()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.tipo is distinct from old.tipo
     or new.sucursal_id is distinct from old.sucursal_id
     or new.activo is distinct from old.activo
     or new.tenant_activo_id is distinct from old.tenant_activo_id then
    if public.current_tenant_rol() <> 'admin'
       or not exists (
         select 1 from public.tenant_miembros m
          where m.user_id = old.id
            and m.tenant_id = public.current_tenant_id()
       ) then
      raise exception 'Solo un admin del tenant puede cambiar rol, sucursal, activo o tenant activo';
    end if;
  end if;
  return new;
end $$;

do $$
declare
  t record;
  cond text;
  admin_cond text;
  editable text[] := array[
    'caja_caja', 'caja_gasto', 'caja_arqueo',
    'clientes_cliente', 'clientes_cuentamovimiento', 'clientes_proveedor',
    'compras_compra', 'compras_detallecompra',
    'descuentos_promocion', 'descuentos_productopromocion', 'descuentos_regladescuento',
    'facturacion_factura', 'facturacion_detallefactura', 'facturacion_pago',
    'facturacion_cuota', 'facturacion_autofactura', 'facturacion_detalleautofactura',
    'logistica_notaremision', 'logistica_transportista', 'logistica_zona',
    'presupuestos_presupuesto', 'presupuestos_detallepresupuesto',
    'productos_producto', 'productos_marca', 'productos_preciocliente',
    'productos_productoasociado',
    'stock_lote', 'stock_movimientostock',
    'sucursales_sucursal', 'sucursales_stocksucursal', 'sucursales_transferenciastock',
    'vendedores_vendedor', 'vendedores_puesto'
  ];
begin
  for t in
    select tablename
      from pg_tables
     where schemaname = 'public'
       and tablename not like 'pg_%'
       and tablename not in ('tenants', 'tenant_miembros', 'perfiles')
     order by tablename
  loop
    execute format('drop policy if exists admin_%I on public.%I', t.tablename, t.tablename);
    execute format('drop policy if exists vendedor_select_%I on public.%I', t.tablename, t.tablename);
    execute format('drop policy if exists vendedor_write_%I on public.%I', t.tablename, t.tablename);
    execute format('drop policy if exists tenant_select_%I on public.%I', t.tablename, t.tablename);
    execute format('drop policy if exists tenant_write_%I on public.%I', t.tablename, t.tablename);
    execute format('drop policy if exists tenant_audit_insert_%I on public.%I', t.tablename, t.tablename);

    cond := 'tenant_id = public.current_tenant_id()';
    if exists (
      select 1 from information_schema.columns
       where table_schema = 'public'
         and table_name = t.tablename
         and column_name = 'sucursal_id'
    ) then
      cond := cond || ' and (sucursal_id is null or sucursal_id = public.current_sucursal_id())';
    end if;

    admin_cond := 'public.current_tenant_rol() = ''admin'' and tenant_id = public.current_tenant_id()';

    execute format(
      'create policy admin_%I on public.%I for all to authenticated '
      'using (%s) with check (%s)',
      t.tablename, t.tablename, admin_cond, admin_cond
    );
    execute format(
      'create policy tenant_select_%I on public.%I for select to authenticated using (%s)',
      t.tablename, t.tablename, cond
    );

    if t.tablename = any(editable)
       or t.tablename in ('common_secuencia', 'facturacion_timbrado') then
      execute format(
        'create policy tenant_write_%I on public.%I for all to authenticated '
        'using (%s) with check (%s)',
        t.tablename, t.tablename, cond, cond
      );
    elsif t.tablename = 'common_auditlog' then
      execute format(
        'create policy tenant_audit_insert_%I on public.%I for insert to authenticated '
        'with check (tenant_id = public.current_tenant_id())',
        t.tablename, t.tablename
      );
    end if;

    -- Incluye las RPCs SECURITY DEFINER: sin esto podrían filtrar otro tenant.
    execute format('alter table public.%I force row level security', t.tablename);
  end loop;
end $$;

