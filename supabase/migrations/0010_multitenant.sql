drop function if exists public.siguiente_numero(text);
create or replace function public.siguiente_numero(
  p_prefijo text,
  p_tenant_id bigint default null
)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tenant_id bigint := coalesce(p_tenant_id, public.current_tenant_id());
  v_ultimo integer;
  v_maximo integer;
begin
  if v_tenant_id is null then
    raise exception 'No hay tenant activo para numerar %', p_prefijo
      using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(hashtext(v_tenant_id::text || ':' || p_prefijo));

  insert into public.common_secuencia (tenant_id, prefijo, ultimo_numero)
  values (v_tenant_id, p_prefijo, 0)
  on conflict (tenant_id, prefijo) do nothing;

  select ultimo_numero into v_ultimo
    from public.common_secuencia
   where tenant_id = v_tenant_id and prefijo = p_prefijo
   for update;

  if v_ultimo = 0 then
    select max(split_part(numero, '-', 2)::integer)
      into v_maximo
      from (
        select numero from public.facturacion_factura
         where tenant_id = v_tenant_id and numero like p_prefijo || '-%'
        union all select numero from public.compras_compra
         where tenant_id = v_tenant_id and numero like p_prefijo || '-%'
        union all select numero from public.presupuestos_presupuesto
         where tenant_id = v_tenant_id and numero like p_prefijo || '-%'
        union all select numero from public.logistica_notaremision
         where tenant_id = v_tenant_id and numero like p_prefijo || '-%'
      ) s;
    v_ultimo := coalesce(v_maximo, 0);
  end if;

  v_ultimo := v_ultimo + 1;

  update public.common_secuencia
     set ultimo_numero = v_ultimo
   where tenant_id = v_tenant_id and prefijo = p_prefijo;

  return p_prefijo || '-' || lpad(v_ultimo::text, 6, '0');
end $$;

revoke all on function public.siguiente_numero(text, bigint) from public;
grant execute on function public.siguiente_numero(text, bigint) to authenticated, service_role;

create or replace function public.asignar_numero_trigger()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_prefijo text;
begin
  if tg_table_name = 'facturacion_factura' then
    v_prefijo := case when new.tipo = 'ticket' then 'TKT' else 'FAC' end;
  elsif tg_table_name = 'compras_compra' then
    v_prefijo := 'COM';
  elsif tg_table_name = 'presupuestos_presupuesto' then
    v_prefijo := 'PRE';
  elsif tg_table_name = 'logistica_notaremision' then
    v_prefijo := 'REM';
  else
    return new;
  end if;

  if new.numero is null or new.numero = '' then
    new.numero := public.siguiente_numero(v_prefijo, new.tenant_id);
  end if;
  return new;
end $$;

-- ---------------------------------------------------------------------------
-- 4b. Documentos electrónicos: RPCs de service_role con tenant explícito.
-- ---------------------------------------------------------------------------

-- Mantienen su dueño original (bypass RLS) porque las llama factpy-emitter con
-- service_role, sin auth.uid(). La Edge Function resuelve la membresía del
-- usuario y envía p_tenant_id; acá se valida en cada INSERT/UPDATE.
drop function if exists public.registrar_documento_electronico(jsonb, jsonb);
create or replace function public.registrar_documento_electronico(
  p_payload jsonb,
  p_respuesta jsonb default null,
  p_tenant_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tenant_id bigint := coalesce(p_tenant_id, public.current_tenant_id());
  v_sucursal_id bigint;
  v_id bigint;
  v_status text := p_respuesta->>'status';
  v_estado public.documento_electronico_estado;
begin
  if v_tenant_id is null or not exists (select 1 from public.tenants where id = v_tenant_id) then
    raise exception 'Tenant inválido para registrar el documento' using errcode = '42501';
  end if;
  if exists (
    select 1 from public.documentos_electronicos
     where receiptid = p_payload->>'receiptid' and tenant_id <> v_tenant_id
  ) then
    raise exception 'El receiptid pertenece a otra empresa' using errcode = '42501';
  end if;

  v_sucursal_id := nullif(p_payload->>'sucursal_id', '')::bigint;
  if v_sucursal_id is not null and not exists (
    select 1 from public.sucursales_sucursal
     where id = v_sucursal_id and tenant_id = v_tenant_id
  ) then
    v_sucursal_id := null;
  end if;

  if v_status = 'true' then
    v_estado := 'aprobado';
  elsif v_status = 'false' then
    v_estado := 'rechazado';
  else
    v_estado := 'enviando';
  end if;

  insert into public.documentos_electronicos (
    tenant_id, receiptid, tipo_documento, referencia_tabla, referencia_id,
    sucursal_id, creado_por, estado, payload, respuesta, cdc, cdc_space,
    xml_url, kude_url, link_consulta, mensaje_error, intentos, enviado_en, aprobado_en
  )
  values (
    v_tenant_id,
    p_payload->>'receiptid',
    coalesce(p_payload->>'tipo_documento', 'desconocido'),
    coalesce(p_payload->>'referencia_tabla', 'desconocida'),
    nullif(p_payload->>'referencia_id', '')::bigint,
    v_sucursal_id,
    nullif(p_payload->>'creado_por', '')::uuid,
    v_estado,
    p_payload,
    coalesce(p_respuesta, '{}'::jsonb),
    p_respuesta->>'cdc',
    p_respuesta->>'cdcSpace',
    p_respuesta->>'xmlLink',
    p_respuesta->>'kude',
    p_respuesta->>'link',
    case when v_status = 'false' then p_respuesta->>'code' else null end,
    1,
    now(),
    case when v_status = 'true' then now() else null end
  )
  on conflict (receiptid) do update
  set estado = excluded.estado,
      respuesta = excluded.respuesta,
      cdc = coalesce(excluded.cdc, public.documentos_electronicos.cdc),
      cdc_space = coalesce(excluded.cdc_space, public.documentos_electronicos.cdc_space),
      xml_url = coalesce(excluded.xml_url, public.documentos_electronicos.xml_url),
      kude_url = coalesce(excluded.kude_url, public.documentos_electronicos.kude_url),
      link_consulta = coalesce(excluded.link_consulta, public.documentos_electronicos.link_consulta),
      mensaje_error = excluded.mensaje_error,
      intentos = public.documentos_electronicos.intentos + 1,
      actualizado_en = now(),
      aprobado_en = coalesce(excluded.aprobado_en, public.documentos_electronicos.aprobado_en)
  where public.documentos_electronicos.tenant_id = v_tenant_id
  returning id into v_id;

  return v_id;
end $$;

drop function if exists public.actualizar_estado_documento_electronico(text, text, jsonb);
create or replace function public.actualizar_estado_documento_electronico(
  p_receiptid text,
  p_estado text,
  p_respuesta jsonb default null,
  p_tenant_id bigint default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tenant_id bigint := coalesce(p_tenant_id, public.current_tenant_id());
  v_estado public.documento_electronico_estado;
begin
  if v_tenant_id is null then
    raise exception 'Tenant inválido para actualizar el documento' using errcode = '42501';
  end if;

  v_estado := case lower(coalesce(p_estado, ''))
    when 'aprobado' then 'aprobado'
    when 'rechazado' then 'rechazado'
    when 'procesando' then 'procesando'
    when 'cancelado' then 'cancelado'
    else 'enviando'
  end;

  update public.documentos_electronicos
  set estado = v_estado,
      respuesta = coalesce(p_respuesta, respuesta),
      cdc = coalesce(p_respuesta->>'cdc', cdc),
      mensaje_error = coalesce(p_respuesta->>'mensaje', mensaje_error),
      actualizado_en = now(),
      aprobado_en = case when v_estado = 'aprobado' then coalesce(aprobado_en, now()) else aprobado_en end
  where receiptid = p_receiptid
    and tenant_id = v_tenant_id;
end $$;

revoke all on function public.registrar_documento_electronico(jsonb, jsonb, bigint) from public;
revoke all on function public.actualizar_estado_documento_electronico(text, text, jsonb, bigint) from public;
grant execute on function public.registrar_documento_electronico(jsonb, jsonb, bigint) to service_role;
grant execute on function public.actualizar_estado_documento_electronico(text, text, jsonb, bigint) to service_role;

