-- 3. tenant_id en las tablas de negocio.
-- ---------------------------------------------------------------------------

do $$
declare
  t record;
begin
  for t in
    select tablename
      from pg_tables
     where schemaname = 'public'
       and tablename not like 'pg_%'
       and tablename not in ('tenants', 'tenant_miembros', 'perfiles')
     order by tablename
  loop
    execute format('alter table public.%I add column if not exists tenant_id bigint', t.tablename);
    execute format('update public.%I set tenant_id = 1 where tenant_id is null', t.tablename);
    execute format('alter table public.%I alter column tenant_id set not null', t.tablename);
    execute format('alter table public.%I alter column tenant_id set default public.current_tenant_id()', t.tablename);

    execute format('alter table public.%I drop constraint if exists %I',
                   t.tablename, t.tablename || '_tenant_id_fkey');
    execute format(
      'alter table public.%I add constraint %I foreign key (tenant_id) '
      'references public.tenants (id) on delete restrict',
      t.tablename, t.tablename || '_tenant_id_fkey'
    );
  end loop;
end $$;

