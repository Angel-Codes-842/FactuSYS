-- 7. Dueño de las RPCs de negocio: sin BYPASSRLS, con RLS del tenant activo.
-- ---------------------------------------------------------------------------

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'factusys_rpc') then
    create role factusys_rpc nologin;
  end if;

  -- ALTER ... OWNER exige poder SET ROLE al nuevo dueño. En Supabase el SQL
  -- Editor corre como postgres, que no es miembro automático del rol recién
  -- creado; en local puede ser otro usuario. Otorgarlo a quien ejecuta la
  -- migración y a postgres cubre ambos casos.
  execute format('grant factusys_rpc to %I', current_user);
  if current_user <> 'postgres'
     and exists (select 1 from pg_roles where rolname = 'postgres') then
    grant factusys_rpc to postgres;
  end if;
end $$;

-- Hereda las políticas `to authenticated` sin dejar de ser un rol separado;
-- auth.uid() sigue leyendo el claim del usuario real de la petición.
grant authenticated to factusys_rpc;
grant usage on schema public, auth to factusys_rpc;
grant execute on function auth.uid() to factusys_rpc;
grant all privileges on all tables in schema public to factusys_rpc;
grant all privileges on all sequences in schema public to factusys_rpc;

do $$
declare
  fn record;
  permitidas text[] := array[
    -- Las tres RPC de documentos-electronicos quedan con su dueño original:
    -- las llama factpy-emitter con service_role y reciben p_tenant_id.
    'siguiente_numero', 'sincronizar_stock_producto',
    'saldo_cliente', 'calcular_totales_factura',
    'crear_factura', 'anular_factura', 'registrar_pago_factura', 'pagar_cuota',
    'crear_nota', 'abrir_caja', 'cerrar_caja', 'recibir_compra',
    'aprobar_transferencia', 'convertir_presupuesto',
    'cuenta_corriente', 'registrar_movimiento_cuenta', 'precio_cliente',
    'marcar_entregado', 'rechazar_nota', 'dashboard', 'ventas_7_dias',
    'crear_compra', 'crear_presupuesto', 'crear_autofactura',
    'crear_factura_pos', 'registrar_arqueo', 'reabrir_caja', 'editar_apertura_caja'
  ];
begin
  -- Quedan fuera: current_* / exigir_operador / usuario_me / email_por_username
  -- (identidad y login), auditar(), los triggers de Auth/perfil y las RPCs de
  -- documentos electrónicos (llamadas por service_role con tenant explícito).
  for fn in
    select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) as args
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
       and p.prosecdef
       and p.proname = any(permitidas)
  loop
    execute format(
      'alter function public.%I(%s) owner to factusys_rpc',
      fn.proname, fn.args
    );
  end loop;
end $$;

