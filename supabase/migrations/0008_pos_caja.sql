-- 0008 — POS, arqueo de caja y cajas pendientes.
--
-- Porta a Supabase las reglas del POS/control de caja de `panaderia`:
--   * pagos mixtos (efectivo / transferencia / tarjeta) en la misma factura;
--   * cierre con conteo de billetes y monedas (arqueo) y diferencia;
--   * cajas de días anteriores que quedaron abiertas;
--   * reapertura y corrección del monto de apertura con auditoría.
--
-- Se ejecuta después de 0007_defaults.sql. Idempotente: usa create or
-- replace / if not exists y drop policy antes de crear cada política.

-- ---------------------------------------------------------------------------
-- Arqueo de caja.
-- ---------------------------------------------------------------------------

create table if not exists public.caja_arqueo (
  id bigint generated by default as identity primary key,
  caja_id bigint not null references public.caja_caja (id) on delete cascade,
  denominaciones jsonb not null default '{}'::jsonb,
  total_contado numeric(14,2) not null default 0,
  esperado numeric(14,2) not null default 0,
  diferencia numeric(14,2) not null default 0,
  observaciones text not null default '',
  usuario_id uuid references public.perfiles (id) on delete set null,
  creado timestamptz not null default now()
);

create index if not exists caja_arqueo_caja_id_idx on public.caja_arqueo (caja_id);

alter table public.caja_arqueo enable row level security;

drop policy if exists arqueo_select_operadores on public.caja_arqueo;
create policy arqueo_select_operadores on public.caja_arqueo
  for select to authenticated
  using (public.current_tipo() in ('admin', 'vendedor'));

revoke all on public.caja_arqueo from anon;
revoke insert, update, delete on public.caja_arqueo from authenticated;
grant select on public.caja_arqueo to authenticated;

-- ---------------------------------------------------------------------------
-- Vista de caja por medio de pago.
--
-- La versión de 0004 sumaba f.total (todas las ventas) al esperado, así que
-- una venta con tarjeta/transferencia/crédito inflaba el efectivo esperado.
-- Acá el esperado es apertura + efectivo - egresos, igual que en panadería.
-- ---------------------------------------------------------------------------

-- El orden de columnas cambia respecto de 0004 (se agregan totales por medio
-- de pago), así que CREATE OR REPLACE no alcanza: Postgres no permite
-- renombrar columnas existentes de una vista.
drop view if exists public.v_cajas;
create view public.v_cajas with (security_invoker = true) as
with resumen as (
  select c.id as caja_id,
         coalesce((
           select sum(f.total)
             from public.facturacion_factura f
            where not f.anulada
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as ventas_total,
         coalesce((
           select sum(p.monto)
             from public.facturacion_pago p
             join public.facturacion_factura f on f.id = p.factura_id
            where not f.anulada
              and p.metodo = 'efectivo'
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as efectivo_total,
         coalesce((
           select sum(p.monto)
             from public.facturacion_pago p
             join public.facturacion_factura f on f.id = p.factura_id
            where not f.anulada
              and p.metodo = 'transferencia'
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as transferencia_total,
         coalesce((
           select sum(p.monto)
             from public.facturacion_pago p
             join public.facturacion_factura f on f.id = p.factura_id
            where not f.anulada
              and p.metodo in ('tarjeta_pos', 'tarjeta')
              and f.fecha_emision >= c.fecha_apertura
              and f.fecha_emision <= coalesce(c.fecha_cierre, now())
              and (c.sucursal_id is null or f.sucursal_id = c.sucursal_id)
         ), 0) as tarjeta_total,
         coalesce((
           select sum(g.monto)
             from public.caja_gasto g
            where g.caja_id = c.id
         ), 0) as gastos_total
    from public.caja_caja c
)
select c.*,
       r.ventas_total,
       r.efectivo_total,
       r.transferencia_total,
       r.tarjeta_total,
       r.gastos_total,
       c.monto_inicial + r.efectivo_total - r.gastos_total as monto_final_esperado,
       c.monto_final_real - (c.monto_inicial + r.efectivo_total - r.gastos_total) as diferencia,
       exists (select 1 from public.caja_arqueo a where a.caja_id = c.id) as tiene_arqueo,
       coalesce(s.nombre, '') as sucursal_nombre,
       pa.username as usuario_apertura_nombre,
       pc.username as usuario_cierre_nombre
  from public.caja_caja c
  join resumen r on r.caja_id = c.id
  left join public.sucursales_sucursal s on s.id = c.sucursal_id
  left join public.perfiles pa on pa.id = c.usuario_apertura_id
  left join public.perfiles pc on pc.id = c.usuario_cierre_id;

grant select on public.v_cajas to authenticated;

-- ---------------------------------------------------------------------------
-- POS: crear_factura_pos envuelve crear_factura y reemplaza el pago fijo en
-- efectivo por los pagos reales del carrito. Si no vienen pagos, conserva el
-- comportamiento anterior (contado => un pago en efectivo; ticket => sin pago).
-- ---------------------------------------------------------------------------

create or replace function public.crear_factura_pos(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
  v_tipo text := p->>'tipo';
  v_total numeric(14,2);
  v_pagos jsonb := coalesce(p->'pagos', '[]'::jsonb);
  v_descuento_pct numeric(5,2) := coalesce((p->>'descuento_porcentaje')::numeric(5,2), 0);
  v_descuento_aplicado numeric(5,2);
  v_descuento_monto numeric(14,2);
  v_base_descuento numeric(14,2);
  v_pago jsonb;
  v_metodo text;
  v_monto numeric(14,2);
  v_suma numeric(14,2) := 0;
begin
  perform public.exigir_operador();

  if jsonb_typeof(v_pagos) <> 'array' then
    raise exception 'pagos debe ser una lista' using errcode = '22023';
  end if;

  v_id := public.crear_factura(p);
  select total into v_total from public.facturacion_factura where id = v_id;

  -- crear_factura guarda descuento_porcentaje pero sólo calcula
  -- descuento_monto cuando una regla de descuento gana. Si el descuento viene
  -- del POS, completamos el monto y recalculamos con la misma base que
  -- calcular_totales_factura (redondeo por línea, como en Django).
  if v_descuento_pct > 0 then
    select descuento_porcentaje, descuento_monto
      into v_descuento_aplicado, v_descuento_monto
      from public.facturacion_factura where id = v_id;
    if v_descuento_aplicado = v_descuento_pct and coalesce(v_descuento_monto, 0) = 0 then
      select coalesce(sum(round(
               d.cantidad * case when d.iva_incluido
                 then round(d.precio_unitario / 1.1, 0)
                 else d.precio_unitario end, 0)), 0)
        into v_base_descuento
        from public.facturacion_detallefactura d
       where d.factura_id = v_id;
      update public.facturacion_factura
         set descuento_monto = round(v_base_descuento * v_descuento_pct / 100, 0)
       where id = v_id;
      perform public.calcular_totales_factura(v_id);
      select total into v_total from public.facturacion_factura where id = v_id;
    end if;
  end if;

  if v_tipo = 'ticket' and p->>'numero' is null then
    update public.facturacion_factura
       set numero = public.siguiente_numero('T')
     where id = v_id;
  end if;

  -- crear_factura ya insertó un pago único para contado; se descarta para que
  -- el desglose del POS sea la única fuente de pagos de esa factura.
  if v_tipo = 'contado' and jsonb_array_length(v_pagos) > 0 then
    delete from public.facturacion_pago where factura_id = v_id;
  end if;

  for v_pago in select value from jsonb_array_elements(v_pagos) loop
    v_metodo := case v_pago->>'metodo'
                  when 'tarjeta' then 'tarjeta_pos'
                  when 'qr' then 'transferencia'
                  else v_pago->>'metodo'
                end;
    if v_metodo not in ('efectivo', 'transferencia', 'tarjeta_pos', 'cheque') then
      raise exception 'Método de pago no válido: %', coalesce(v_pago->>'metodo', '') using errcode = '22023';
    end if;

    v_monto := coalesce((v_pago->>'monto')::numeric, 0);
    if v_monto < 0 then
      raise exception 'Los montos de pago no pueden ser negativos' using errcode = '22023';
    end if;
    if v_monto = 0 then
      continue;
    end if;

    if v_tipo = 'credito' then
      -- Abono inicial: registrar_pago_factura también actualiza cuotas y
      -- cuenta corriente.
      perform public.registrar_pago_factura(v_id, v_monto, v_metodo);
    else
      insert into public.facturacion_pago (monto, fecha, metodo, factura_id, usuario_id)
      values (v_monto, now(), v_metodo, v_id, auth.uid());
    end if;
    v_suma := v_suma + v_monto;
  end loop;

  if v_tipo = 'credito' then
    if v_suma > v_total + 0.01 then
      raise exception 'El abono no puede superar el total de la venta' using errcode = '22023';
    end if;
  elsif jsonb_array_length(v_pagos) > 0 and abs(v_suma - v_total) > 0.01 then
    raise exception 'Los pagos deben sumar el total de la venta (%)', v_total using errcode = '22023';
  end if;

  return v_id;
end $$;

-- ---------------------------------------------------------------------------
-- Cierre con arqueo.
-- ---------------------------------------------------------------------------

create or replace function public.registrar_arqueo(
  p_caja_id bigint,
  p_denominaciones jsonb,
  p_observaciones text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_esperado numeric(14,2);
  v_contado numeric(14,2) := 0;
  v_clave text;
  v_valor numeric;
  v_resultado jsonb;
begin
  perform public.exigir_operador();

  if jsonb_typeof(p_denominaciones) <> 'object' then
    raise exception 'El conteo de billetes y monedas no es válido' using errcode = '22023';
  end if;

  for v_clave, v_valor in
    select key, (value::text)::numeric from jsonb_each(p_denominaciones)
  loop
    if v_clave !~ '^[0-9]+$' or v_clave::numeric <= 0 then
      raise exception 'Denominación no válida: %', v_clave using errcode = '22023';
    end if;
    if v_valor < 0 or v_valor <> floor(v_valor) then
      raise exception 'Las cantidades del arqueo deben ser enteros mayores o iguales a 0' using errcode = '22023';
    end if;
    v_contado := v_contado + v_clave::numeric * v_valor;
  end loop;

  select monto_final_esperado into v_esperado
    from public.v_cajas where id = p_caja_id and estado = 'abierta';
  if not found then
    raise exception 'Caja no encontrada o ya cerrada' using errcode = 'P0002';
  end if;

  perform public.cerrar_caja(p_caja_id, v_contado, coalesce(p_observaciones, ''));

  insert into public.caja_arqueo (
    caja_id, denominaciones, total_contado, esperado, diferencia,
    observaciones, usuario_id
  ) values (
    p_caja_id, p_denominaciones, v_contado, v_esperado, v_contado - v_esperado,
    coalesce(p_observaciones, ''), auth.uid()
  );

  perform public.auditar(
    'CERRAR_CAJA', 'Caja', p_caja_id::text,
    jsonb_build_object(
      'esperado', v_esperado, 'contado', v_contado,
      'diferencia', v_contado - v_esperado, 'denominaciones', p_denominaciones
    )
  );

  select jsonb_build_object(
    'esperado', v_esperado, 'real', v_contado,
    'diferencia', v_contado - v_esperado, 'denominaciones', p_denominaciones
  ) into v_resultado;
  return v_resultado;
end $$;

-- ---------------------------------------------------------------------------
-- Reapertura y corrección de apertura.
-- ---------------------------------------------------------------------------

create or replace function public.reabrir_caja(
  p_caja_id bigint,
  p_motivo text default ''
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_caja public.caja_caja%rowtype;
begin
  perform public.exigir_operador();

  select * into v_caja from public.caja_caja where id = p_caja_id for update;
  if not found then
    raise exception 'Caja no encontrada' using errcode = 'P0002';
  end if;
  if v_caja.estado <> 'cerrada' then
    raise exception 'La caja ya está abierta' using errcode = '23514';
  end if;

  update public.caja_caja
     set estado = 'abierta',
         fecha_cierre = null,
         monto_final_real = null,
         usuario_cierre_id = null
   where id = p_caja_id;

  delete from public.caja_arqueo where caja_id = p_caja_id;

  perform public.auditar(
    'REABRIR_CAJA', 'Caja', p_caja_id::text,
    jsonb_build_object(
      'fecha', v_caja.fecha_apertura,
      'cierre_real_previo', v_caja.monto_final_real,
      'motivo', coalesce(nullif(p_motivo, ''), 'Reapertura de caja')
    )
  );
end $$;

create or replace function public.editar_apertura_caja(
  p_caja_id bigint,
  p_monto_inicial numeric,
  p_motivo text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_anterior numeric(14,2);
begin
  perform public.exigir_operador();

  if coalesce(p_monto_inicial, -1) < 0 then
    raise exception 'Ingresá un monto de apertura válido (0 o mayor)' using errcode = '22023';
  end if;

  select monto_inicial into v_anterior
    from public.caja_caja
   where id = p_caja_id and estado = 'abierta'
   for update;
  if not found then
    raise exception 'Caja abierta no encontrada' using errcode = 'P0002';
  end if;

  update public.caja_caja
     set monto_inicial = p_monto_inicial
   where id = p_caja_id;

  perform public.auditar(
    'EDITAR_APERTURA_CAJA', 'Caja', p_caja_id::text,
    jsonb_build_object(
      'apertura_anterior', v_anterior,
      'apertura_nueva', p_monto_inicial,
      'motivo', coalesce(nullif(p_motivo, ''), 'Corrección de monto inicial')
    )
  );

  return jsonb_build_object('apertura_anterior', v_anterior, 'apertura_nueva', p_monto_inicial);
end $$;

-- Cajas abiertas de días anteriores (hora de Asunción, no del servidor).
create or replace function public.caja_pendientes()
returns jsonb
language sql
stable
set search_path = public, pg_temp
as $$
  select coalesce(jsonb_agg(to_jsonb(v) order by v.fecha_apertura), '[]'::jsonb)
    from public.v_cajas v
   where v.estado = 'abierta'
     and (v.fecha_apertura at time zone 'America/Asuncion')::date
         < (now() at time zone 'America/Asuncion')::date;
$$;

